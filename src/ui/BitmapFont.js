export const GLYPH_W = 5;
export const GLYPH_H = 7;

// Rendered glyphs are cached per (char, colour, scale). Drawing a string
// pixel-by-pixel with fillRect costs ~35 calls per character; caching to a tiny
// canvas and blitting costs one drawImage.
const cache = new Map();

function glyphCanvas(ch, color, scale) {
  const key = `${ch}|${color}|${scale}`;
  let c = cache.get(key);
  if (c) return c;
  const rows = G[ch] ?? G['?'];
  const cv = document.createElement('canvas');
  cv.width = GLYPH_W * scale;
  cv.height = GLYPH_H * scale;
  const cx = cv.getContext('2d');
  cx.imageSmoothingEnabled = false;
  cx.fillStyle = color;
  for (let y = 0; y < GLYPH_H; y++) {
    const bits = rows[y];
    for (let x = 0; x < GLYPH_W; x++) {
      if (bits & (1 << (GLYPH_W - 1 - x))) {
        cx.fillRect(x * scale, y * scale, scale, scale);
      }
    }
  }
  cache.set(key, cv);
  return cv;
}

export function textWidth(text, scale = 1, tracking = 1) {
  if (!text) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/**
 * Draw text. Coordinates are the top-left of the first glyph unless `align`
 * says otherwise, and everything is snapped to whole pixels.
 *
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x @param {number} y
 * @param {{scale?:number, color?:string, align?:'left'|'center'|'right',
 *          tracking?:number, shadow?:string|null}} [opts]
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const {
    scale = 1, color = '#ffffff', align = 'left',
    tracking = 1, shadow = '#000000',
  } = opts;
  if (!text) return;
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale, tracking);
  let px = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const py = Math.round(y);
  const step = (GLYPH_W + tracking) * scale;

  // A one-pixel drop shadow is what keeps the HUD readable over a bright road.
  if (shadow) {
    let sx = px;
    for (const ch of str) {
      if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, shadow, scale), sx + scale, py + scale);
      sx += step;
    }
  }
  for (const ch of str) {
    if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, color, scale), px, py);
    px += step;
  }
}

/** Clear the glyph cache. Only needed if a palette changes at runtime. */
export function clearFontCache() {
  cache.clear();
}
